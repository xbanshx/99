window.currentLang = localStorage.getItem("lang") || "ar";

function switchLang(lang) {
    window.currentLang = lang;
    localStorage.setItem("lang", lang);

    const html = document.documentElement;
    html.lang = lang;
    html.dir = lang === "ar" ? "rtl" : "ltr";

    const dict = mediaTranslations[lang] || mediaTranslations.ar;

    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        if (dict[key]) el.textContent = dict[key];
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (dict[key]) el.setAttribute("placeholder", dict[key]);
    });

    const btn = document.getElementById("lang-toggle");
    if (btn) {
        btn.textContent = lang === "ar" ? "EN" : "عربي";
        btn.setAttribute("aria-label", lang === "ar" ? "Switch to English" : "التبديل إلى العربية");
    }

    document.title = lang === "en"
        ? "99 Media | Broadcast, Cinema & AI Video Production House in Jeddah | i99.sa"
        : "99 Media | دار الإنتاج الإعلامي والسينمائي وفيديوهات الذكاء الاصطناعي من جدة | i99.sa";

    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) {
        metaDesc.setAttribute(
            "content",
            lang === "en"
                ? "99 Media in Jeddah (est. 2014): broadcast and cinema production, AI video creation, corporate PR, and digital campaigns — trusted by MBC, SBA, Misk, and Al Faisaliah."
                : "99 للإعلام (منذ 2014 في جدة): دار إنتاج تلفزيوني وسينمائي ورقمي، فيديوهات الذكاء الاصطناعي، الاتصال المؤسسي والعلاقات العامة، والتسويق الرقمي — شركاء MBC وهيئة الإذاعة والتلفزيون ومسك والفيصلية."
        );
    }

    document.dispatchEvent(new CustomEvent("media:langchange", { detail: { lang } }));
}

document.addEventListener("DOMContentLoaded", () => {
    switchLang(window.currentLang);
});
